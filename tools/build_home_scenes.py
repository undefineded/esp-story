"""Convert the approved 2x2 illustration sheet to flash-resident swap565 sprites."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
source = Image.open(ROOT / 'docs/icons/home-scenes.png').convert('RGBA')
w, h = source.size
backgrounds = ['#f9dfad', '#dcebd5', '#f8dfd4', '#e2e3f3']
lines = ['// Generated by tools/build_home_scenes.py; 128x128, byte-swapped RGB565.',
         '#pragma once', '#include <stdint.h>']
for i, background in enumerate(backgrounds):
    crop = source.crop(((i % 2)*w//2, (i//2)*h//2, (i % 2+1)*w//2, (i//2+1)*h//2))
    crop = crop.resize((128, 128), Image.Resampling.LANCZOS)
    flat = Image.new('RGBA', crop.size, background)
    flat.alpha_composite(crop)
    values = []
    for r, g, b, _ in flat.getdata():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        values.append((v >> 8) | ((v & 255) << 8))
    lines.append(f'static const uint16_t HOME_SCENE_{i}[128 * 128] = {{')
    for n in range(0, len(values), 16):
        lines.append('  ' + ','.join(f'0x{v:04x}' for v in values[n:n+16]) + ',')
    lines.append('};')
lines.append('static const uint16_t* const HOME_SCENES[] = {HOME_SCENE_0, HOME_SCENE_1, HOME_SCENE_2, HOME_SCENE_3};')
(ROOT / 'src/home_scenes.h').write_text('\n'.join(lines) + '\n')
print('Generated four 128x128 sprites: 131072 bytes in flash')
