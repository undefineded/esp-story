"""Bake the video theater illustration into the home-screen RGB565 sprite."""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
image = Image.open(root / 'docs/icons/video-theater.png').convert('RGBA')
image = image.resize((128, 128), Image.Resampling.LANCZOS)
flat = Image.new('RGBA', image.size, '#f8dfd4')
flat.alpha_composite(image)
values = []
for r, g, b, _ in flat.getdata():
    value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    values.append((value >> 8) | ((value & 255) << 8))
lines = ['// Generated by tools/build_video_theater.py; 128x128 byte-swapped RGB565.',
         '#pragma once', '#include <stdint.h>',
         'static const uint16_t HOME_VIDEO_SCENE[128 * 128] = {']
for n in range(0, len(values), 16):
    lines.append('  ' + ','.join(f'0x{v:04x}' for v in values[n:n+16]) + ',')
lines.append('};')
(root / 'src/home_video_scene.h').write_text('\n'.join(lines) + '\n')
